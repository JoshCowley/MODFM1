#!/usr/bin/env python3
"""make_font.py {gen}: FM1 Rack's own typefaces (update 51), written over fm1-base's felucca_font.h after it.

fm1-base renders Barlow Semi Condensed (SemiBold and Bold). Josh found it heavy; FM1 Rack sets IBM Plex Sans
Condensed instead, a lighter, more engineered face that keeps its shapes at 10-15 px, with tabular figures so values
don't jump about as they change. The fonts are in fonts/ (SIL Open Font License 1.1: fonts/OFL-*.txt).

Same format as fm1-base's tools/gen_font.py (MPL-2.0, Charles Vestal, Leo Kuroshita), whose render() this follows:
per glyph an advance, a bitmap width and an offset; rows top to bottom, two pixels a byte (high nibble first), alpha
0..15. (Geist was tried beside it for update 51; Josh kept Plex.)"""
import os
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent / "fonts"
PAD = 2
PLEX = "ibm-plex-sans-condensed-latin-{}-normal.woff"
# role: (file, px, first, last). T footers and labels (capitals and digits), XS hints, S body, B names and values,
# M and L (the splash: not linked on the device). The pixel sizes keep each role's line height near the layout's.
# FM1_FONTW (update 53, for the A/B rounds): the weights, labels / values. 1 Medium / SemiBold (update 51),
# 2 Regular / Medium (lighter), 3 SemiBold / Bold (heavier)
W = {"1": (500, 400, 600), "2": (400, 400, 500), "3": (600, 500, 700)}[os.environ.get("FM1_FONTW", "1")]
SETS = {
    "plex": {"T": (PLEX.format(W[0]), 10, 32, 95), "XS": (PLEX.format(W[0]), 12, 32, 126),
             "S": (PLEX.format(W[1]), 14, 32, 126), "B": (PLEX.format(W[2]), 15, 32, 126),
             "M": (PLEX.format(W[2]), 23, 32, 95), "L": (PLEX.format(W[2]), 31, 32, 126)},
}
SET = os.environ.get("FM1_FONTSET", "plex")


def render(name, px, first, last):
    font = ImageFont.truetype(str(HERE / name), px)
    feats = ["tnum"]
    try:
        font.getlength("0", features=feats)
    except Exception:                         # (no raqm: no OpenType features; Plex's figures are tabular anyway)
        feats = None
    asc, desc = font.getmetrics()
    top = max(0, font.getbbox("A8|(", features=feats)[1] - 1)
    h = asc + desc - top
    out = []
    for c in range(first, last + 1):
        ch = chr(c)
        adv = int(round(font.getlength(ch, features=feats)))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD, 0), ch, font=font, fill=255, features=feats)
        img = img.crop((0, top, bw, top + h))
        out.append((adv, bw, [min(15, (v + 8) // 17) for v in img.tobytes()]))
    return h, out


def main(gen):
    lines = [f"/* generated by FM1 Rack's make_font.py: {SET} (fonts/, SIL OFL 1.1) */", "#pragma once",
             "#include <stdint.h>", f"#define FONT_PAD {PAD}", ""]
    for role in ("T", "XS", "S", "B", "M", "L"):
        name, px, first, last = SETS[SET][role]
        h, glyphs = render(name, px, first, last)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        lines.append(f"static const uint8_t FONT_{role}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{role}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{role}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{role}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t FONT_{role} = {{ {h}, {PAD}, {first}, {last}, "
                     f"FONT_{role}_ADV, FONT_{role}_BW, FONT_{role}_OFF, FONT_{role}_DATA }};")
        lines.append("")
        print(f"font {role}: {name} {px}px h {h}, digit {glyphs[ord('0') - first][0]}, {len(data)} B")
    (Path(gen) / "felucca_font.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
