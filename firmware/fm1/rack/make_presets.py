#!/usr/bin/env python3
"""Writes presets.h for the FM1 Rack firmware from the FM-1's factory presets' engine calls
(firmware/tests/presets-fm1-calls.json, written by fm1_presets.py from the page's presets and presets_fm1.py).

  python3 make_presets.py          (from this folder; presets.h is committed, so only after the presets change)
  python3 make_presets.py --full   presets_full.h: the same presets' own calls, whole, for rack_host's check

Every preset whose modules the Lite firmware has (no Elements, Warps, Marbles, Clouds) is kept. INIT is stored
whole; each other preset as what it changes from INIT (its six modules, then every call whose value differs), as
the benchmark's cases.h, which bench_host checked gives the same sound sample for sample. Parameter ranges
(set_meta) depend only on the module in a slot (slots 6-8: on the slot), so they are stored once per module in
META, not per preset; the loader applies them for the modules a preset has. The calls are packed as
bytes (an op, its small numbers as signed bytes, its values as 32-bit floats) to keep the flash small."""
import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent.parent / "tests" / "presets-fm1-calls.json"
LITE_OUT = {3, 11, 22, 30}   # Elements, Warps, Marbles, Clouds

# op: (code, small ints, floats)
OPS = {"set_module": (1, 2, 0), "set_param": (2, 2, 1), "set_meta": (3, 2, 3), "set_route": (4, 4, 2),
       "set_macro": (5, 1, 1), "set_master": (6, 0, 1), "set_master_fx": (7, 0, 4), "set_legato": (8, 0, 1),
       "set_vintage": (9, 0, 1), "set_ext_slew": (10, 1, 1), "set_tune": (11, 1, 1)}
KEYLEN = {"set_module": 1, "set_param": 2, "set_meta": 2, "set_route": 1, "set_macro": 1, "set_master": 0,
          "set_master_fx": 0, "set_legato": 0, "set_vintage": 0, "set_ext_slew": 1, "set_tune": 1}
CATS = ["INIT", "BASS", "LEAD", "PAD", "KEYS", "FX", "OTHER"]


def final_state(calls):
    st = {}
    for c in calls:
        if c[0] == "set_hw" or (c[0] == "set_tune" and c[2] == 0):
            continue
        k = (c[0], *c[1:1 + KEYLEN[c[0]]])
        st.pop(k, None)
        st[k] = c
    return st


def pack(c):
    code, ni, nf = OPS[c[0]]
    a = c[1:]
    if c[0] == "set_route":                     # i, src, slot, param, amount, via
        ints, fl = [a[0], a[1], a[2], a[3]], [a[4], a[5]]
    elif c[0] == "set_module":
        ints, fl = [a[0], a[1]], []
    else:
        ints, fl = list(a[:ni]), list(a[ni:ni + nf])
    for v in ints:
        if not -128 <= int(v) <= 127:
            raise SystemExit(f"make_presets: {c} has a small number out of range")
    return bytes([code, *(int(v) & 0xFF for v in ints)]) + b"".join(struct.pack("<f", float(v)) for v in fl)


def category(name):
    pre = name.split(" ")[0]
    return {"BS": "BASS", "LD": "LEAD", "PD": "PAD", "CH": "KEYS", "FX": "FX", "INIT": "INIT"}.get(pre, "OTHER")


def meta_table(data):
    """(module id, or 100 + slot for slots 6-8) -> {param: (lo, hi, span)}; checks it is the same in every preset"""
    tab = {}
    for p in data:
        mods = {}
        for c in p["calls"]:
            if c[0] == "set_module":
                mods[c[1]] = c[2]
            elif c[0] == "set_meta":
                key = 100 + c[1] if c[1] >= 6 else mods.get(c[1], 0)
                v = tuple(c[3:6])
                if tab.setdefault(key, {}).setdefault(c[2], v) != v:
                    raise SystemExit(f"make_presets: {key} param {c[2]} has two ranges")
    return tab


def full(keep):
    """presets_full.h: each preset's own calls (after INIT's, as the page loads a preset), unpacked"""
    fn = {k: v[0] for k, v in OPS.items()}
    out = ["/* Generated by make_presets.py --full: each kept preset's own calls, for rack_host.c. */", ""]
    rows = []
    for p in keep:
        ident = "FULL_" + "".join(ch if ch.isalnum() else "_" for ch in p["name"])
        out.append(f"static const full_op_t {ident}[] = {{")
        for c in p["calls"]:
            if c[0] == "set_hw":
                continue
            if c[0] == "set_meta":
                o = (13, c[1], c[2], 0, 0, c[3], c[4], c[5], 0)
            elif c[0] == "set_route":
                o = (4, c[1], c[2], c[3], c[4], c[5], c[6], 0, 0)
            elif c[0] == "set_master_fx":
                o = (7, 0, 0, 0, 0, *c[1:5])
            elif c[0] == "set_module":
                o = (1, c[1], c[2], 0, 0, 0, 0, 0, 0)
            elif c[0] == "set_param":
                o = (2, c[1], c[2], 0, 0, c[3], 0, 0, 0)
            elif c[0] in ("set_macro", "set_ext_slew", "set_tune"):
                o = (fn[c[0]], c[1], 0, 0, 0, c[2], 0, 0, 0)
            else:
                o = (fn[c[0]], 0, 0, 0, 0, c[1], 0, 0, 0)
            out.append("    {%d, %d, %d, %d, %d, %rf, %rf, %rf, %rf}," % (*o[:5], *(float(v) for v in o[5:])))
        out.append("};")
        rows.append(f"    {{{ident}, {sum(1 for c in p['calls'] if c[0] != 'set_hw')}}},")
    out += ["static const struct { const full_op_t *ops; int n; } FULL[] = {", *rows, "};", ""]
    (HERE / "presets_full.h").write_text("\n".join(out))
    print(f"presets_full.h: {len(keep)} presets")


OSC_KEYS = ["WAVE", "OCTAVE", "SEMI", "FINE", "PW", "OSC LVL", "MAIN LVL"]   # AMP's parameters 24-30 (engine/rack.cc)


def add_osc(data):
    """the firmware's OSC (the page has none): a preset's "osc" as set_param calls on AMP (slot 6), 24-30"""
    for p in data:
        for k, v in p.get("fm1", {}).get("osc", {}).items():
            p["calls"].append(["set_param", 6, 24 + OSC_KEYS.index(k), float(v)])


def main():
    global CAP
    data = json.loads(SRC.read_text())
    add_osc(data)
    CAP = {p["name"]: p["fm1"]["fm1_voices"] for p in data if p.get("fm1", {}).get("fm1_voices")}
    meta = meta_table(data)
    from func_def import FUNC_ID, func_meta     # FUNC: the firmware's own module: its ranges as func_def has them
    if meta.setdefault(FUNC_ID, func_meta()) != func_meta():
        raise SystemExit("make_presets: FUNC's ranges differ from func_def's")
    byname = {p["name"]: p for p in data}
    init = final_state(byname["INIT"]["calls"])
    keep = [p for p in data if not any(c[0] == "set_module" and c[2] in LITE_OUT for c in p["calls"])]
    keep.sort(key=lambda p: (p["name"] != "INIT", CATS.index(category(p["name"])), data.index(p)))
    if "--full" in sys.argv:
        return full(keep)
    blob, table = bytearray(), []
    for p in keep:
        st = {k: c for k, c in final_state(p["calls"]).items() if c[0] != "set_meta"}
        if p["name"] == "INIT":
            ops = list(st.values())
        else:
            mods = {c[1]: c[2] for c in p["calls"] if c[0] == "set_module"}
            ops = [["set_module", s, mods.get(s, 0)] for s in range(6)]
            ops += [c for k, c in st.items() if c[0] != "set_module" and init.get(k) != c]
            missing = [k for k in init if k not in st and k[0] not in ("set_module", "set_meta")]
            if missing:
                raise SystemExit(f"make_presets: {p['name']} leaves {missing[:3]} as INIT has them")
        at = len(blob)
        for c in ops:
            blob += pack(c)
        v = int(p["voices"])
        if p["name"] in CAP:                    # presets.json "fm1_voices": the FM-1's CPU allows fewer (benchmark)
            v = min(v, CAP[p["name"]])
        table.append((p["name"], category(p["name"]), at, len(blob) - at, v, int(p.get("mode", 0))))
    out = ["/* Generated by make_presets.py from firmware/tests/presets-fm1-calls.json: do not edit. */",
           "/* PRESET_OPS: packed engine calls (app.c run_preset reads them); PRESETS: name, category, where. */", "",
           f"static const uint8_t PRESET_OPS[{len(blob)}] = {{"]
    for i in range(0, len(blob), 24):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in blob[i:i + 24]) + ",")
    out += ["};", "", "static const rk_preset_t PRESETS[] = {"]
    for n, cat, at, ln, v, m in table:
        out.append(f'    {{"{n}", "{cat}", {at}, {ln}, {v}, {m}}},')
    out += ["};", f"#define NPRESETS {len(table)}", "",
            "/* META: each module's parameter ranges (key: module id; 100 + slot for slots 6-8), as param, lo, hi, span */"]
    keys = sorted(meta)
    rows, idx = [], []
    for k in keys:
        idx.append((k, len(rows), len(meta[k])))
        for par, (lo, hi, sp) in sorted(meta[k].items()):
            rows.append(f"    {{{par}, {float(lo)!r}f, {float(hi)!r}f, {float(sp)!r}f}},")
    out += [f"static const rk_meta_t META[{len(rows)}] = {{", *rows, "};",
            "static const struct { uint8_t key; uint16_t at, n; } META_OF[] = {",
            *[f"    {{{k}, {a}, {n}}}," for k, a, n in idx], "};", f"#define NMETA_OF {len(idx)}", ""]
    (HERE / "presets.h").write_text("\n".join(out))
    print(f"presets.h: {len(table)} presets, {len(blob)} bytes of calls")


if __name__ == "__main__":
    sys.exit(main())
