#!/usr/bin/env python3
"""fm1.toml's gen step: units/, one small C++ file per engine source, each including the real one, so fm1-base's
build.py (which takes its o2 units from inside the app's folder) compiles FM1 Rack's engine and the Mutable modules
the Lite firmware has, from where they are."""
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENG = HERE.parent.parent.parent / "engine"
LITE_OUT = ("elements/", "warps/", "clouds/", "marbles/")

units = HERE / "units"
units.mkdir(exist_ok=True)
want = {}
for src in (ENG / "sources.txt").read_text().split():
    if not src.startswith(LITE_OUT):
        want["mi_" + src.replace("/", "_")] = f'#include "{src}"\n'
want["rack.cc"] = '#include "../../../../engine/rack.cc"\n'
want["grids_nodes.cc"] = '#include "../../../../engine/grids_nodes.cc"\n'
want["rt.cc"] = '#include "../rt.cc"\n'
want["rk.cc"] = '#include "../rk.cc"\n'
# as the rack firmware (its make_units.py): Plaits' MODAL with 16 of its 24 resonator modes, so the bench measures it
EUR = Path(os.environ["EURORACK"]) if os.environ.get("EURORACK") else HERE.parent.parent.parent.parent / "eurorack"
mv = (EUR / "plaits" / "dsp" / "physical_modelling" / "modal_voice.cc").read_text()
assert mv.count("resonator_.Init(0.015f, kMaxNumModes);") == 1, "make_units: Plaits' modal_voice.cc changed"
want["mi_plaits_dsp_physical_modelling_modal_voice.cc"] = (
    "// Generated by make_units.py: eurorack's plaits/dsp/physical_modelling/modal_voice.cc with 16 resonator modes\n" +
    mv.replace("resonator_.Init(0.015f, kMaxNumModes);", "resonator_.Init(0.015f, 16);"))
for f in units.glob("*.cc"):
    if f.name not in want:
        f.unlink()
for name, text in want.items():
    f = units / name
    if not f.exists() or f.read_text() != text:
        f.write_text(text)
print(f"units: {len(want)} C++ units")
